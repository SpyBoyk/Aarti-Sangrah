export const searchItems = (query) => {
  const q = query.trim().toLowerCase();
  if (!q) return ITEMS;
  return ITEMS.filter((i) =>
    [i.title, i.hindiTitle, i.deity, i.description, i.language, i.type]
      .join(' ')
      .toLowerCase()
      .includes(q)
  );
};
